function emit(questions) {
  const out = [
    '/* Сливы бейба: Алгоритм-рус + База_данных_ru — автоимпорт */',
    '(function () {',
    '  var Q = window.KTA_QUESTIONS || (window.KTA_QUESTIONS = []);',
    '  var ADD = [',
  ];
  questions.forEach((obj, i) => {
    const parts = [
      `id:${JSON.stringify(obj.id)}`,
      'real:true',
      `subject:${JSON.stringify(obj.subject)}`,
      `topic:${JSON.stringify(obj.topic)}`,
      `type:${JSON.stringify(obj.type || 'single')}`,
      `q:${JSON.stringify(obj.q)}`,
    ];
    if (obj.code) parts.push(`code:${JSON.stringify(obj.code)}`);
    parts.push(
      'options:[' +
        obj.options.map((o) => `{k:${JSON.stringify(o.k)},t:${JSON.stringify(o.t)}}`).join(',') +
        ']'
    );
    parts.push(`correct:${JSON.stringify(obj.correct)}`);
    parts.push(`explain:${JSON.stringify(obj.explain)}`);
    out.push('  {' + parts.join(',') + '}' + (i < questions.length - 1 ? ',' : ''));
  });
  out.push('  ];');
  out.push('  for (var i = 0; i < ADD.length; i++) Q.push(ADD[i]);');
  out.push('})();');
  out.push('');
  return out.join('\n');
}

