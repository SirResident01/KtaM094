function scrub(s) {
  return String(s || '')
    .replace(/<\/?v[a-z]*>/gi, '')
    .replace(/\s+/g, ' ')
    .replace(/\.$/, '')
    .trim();
}
function clip(s, n = 110) {
  s = scrub(s);
  return s.length <= n ? s : s.slice(0, n - 1).trim() + '…';
}
function ansOf(q) {
  const o = (q.options || []).find((x) => (q.correct || []).includes(x.k));
  return scrub(o ? o.t : '');
}
function wrongsOf(q) {
  return (q.options || [])
    .filter((o) => !(q.correct || []).includes(o.k))
    .map((o) => scrub(o.t))
    .filter(Boolean);
}
function cleanQuestion(q) {
  return {
    ...q,
    q: scrub(q.q),
    options: (q.options || []).map((o) => ({ ...o, t: scrub(o.t) })),
  };
}

