function firstFact(list, text) {
  for (const [re, fact] of list) {
    if (re.test(text)) return fact;
  }
  return '';
}

function contrast(ans, wrong) {
  const a = ans.toLowerCase();
  const w = wrong.toLowerCase();
  const na = a.match(/([1-4])-узел/);
  const nw = w.match(/([1-4])-узел/);
  if (na && nw && na[1] !== nw[1]) {
    return `Не «${clip(wrong, 45)}»: у того типа узла другое число ключей/связей.`;
  }
  if (/стек/.test(a) && /очеред/.test(w)) return `Не очередь (FIFO) — нужен стек (LIFO).`;
  if (/очеред/.test(a) && /стек/.test(w)) return `Не стек — по условию нужна очередь (FIFO).`;
  if (/ширин|bfs/.test(a) && /глубин|dfs/.test(w)) return `Не DFS — условие про обход в ширину.`;
  if (/глубин|dfs/.test(a) && /ширин|bfs/.test(w)) return `Не BFS — условие про обход в глубину.`;
  if (/уоршелл/.test(a) && /флойд|дейкстр|прима|крускал|краскал|джонсон|форд/.test(w)) {
    return `Не «${clip(wrong, 30)}»: с Флойдом по схеме матрицы схож именно Уоршелл.`;
  }
  if (/флойд/.test(a) && /уоршелл|дейкстр|прима|крускал|краскал/.test(w)) {
    return `Не «${clip(wrong, 30)}» — Флойд даёт кратчайшие пути между всеми парами.`;
  }
  if (/дейкстр/.test(a) && /флойд|беллман|прима|крускал|краскал/.test(w)) {
    return `Не «${clip(wrong, 30)}» — Дейкстра ищет пути из одной вершины без отрицательных весов.`;
  }
  if (/прима/.test(a) && /крускал|краскал|дейкстр/.test(w)) {
    return `Не «${clip(wrong, 30)}» — Прим растит остов из вершины.`;
  }
  if (/крускал|краскал/.test(a) && /прима|дейкстр/.test(w)) {
    return `Не «${clip(wrong, 30)}» — Краскал идёт по рёбрам, отсортированным по весу.`;
  }
  if (/быстр|quick/.test(a) && /слиян|merge|пузырь|шелл|вставк|выбр|пирамид/.test(w)) {
    return `Не «${clip(wrong, 35)}» — другая идея сортировки.`;
  }
  if (/смещен|всплыв|куч|пирамид/.test(a) && /массив|размер|свободн|нов\w* узел/.test(w)) {
    return `Не про размер массива — успех вставки в кучу = восстановление свойства пирамиды.`;
  }
  return '';
}

function lead(stem, ans) {
  if (/как называется/i.test(stem)) {
    const m = stem.match(/как называется\s+(.+?)\s*\??$/i);
    return m
      ? `По описанию «${clip(m[1], 130)}» это «${clip(ans, 80)}».`
      : `Искомый термин — «${clip(ans, 80)}».`;
  }
  if (/как в алгоритме|как (?:работает|происходит|выполняется|реализуется)/i.test(stem)) {
    return `В этом алгоритме на описанном шаге: «${clip(ans, 100)}».`;
  }
  if (/что делает/i.test(stem)) return `На шаге выполняется: «${clip(ans, 100)}».`;
  if (/что происходит/i.test(stem)) return `Происходит следующее: «${clip(ans, 100)}».`;
  if (/что определяет|от чего зависит|успешность/i.test(stem)) {
    return `Успех операции определяет: «${clip(ans, 100)}».`;
  }
  if (/какой алгоритм/i.test(stem)) return `Подходит алгоритм «${clip(ans, 70)}».`;
  if (/какая структура|какую структуру/i.test(stem)) return `Нужная структура — «${clip(ans, 70)}».`;
  if (/для чего|зачем|чему служит|назначен|зачем нужн/i.test(stem)) {
    return `Зачем это нужно: «${clip(ans, 100)}».`;
  }
  if (/\bне\s+(является|относится)|что не |какое из .* не /i.test(stem)) {
    return `Исключение — «${clip(ans, 80)}» (остальные как раз подходят под правило).`;
  }
  if (/сложн|асимптот|o\(/i.test(stem) || /^o\(/i.test(ans)) {
    return `Оценка сложности — «${clip(ans, 40)}».`;
  }
  if (/результат|чему равен|выведет|сколько|чему равн/i.test(stem)) {
    return `Получается «${clip(ans, 60)}».`;
  }
  if (/^куда |^где /i.test(stem)) return `Элемент/связь оказывается так: «${clip(ans, 100)}».`;
  if (/^что такое|^что означает|^что представляет|^что значит/i.test(stem)) {
    return `Имеется в виду: «${clip(ans, 90)}».`;
  }
  if (/^чем |^в чём |^каким образом/i.test(stem)) {
    return `Отличие/способ: «${clip(ans, 100)}».`;
  }
  if (/^когда |^в каком случае/i.test(stem)) {
    return `Это бывает, когда: «${clip(ans, 100)}».`;
  }
  if (/^почему /i.test(stem)) return `Причина: «${clip(ans, 100)}».`;
  if (/^какой |^какая |^какое |^какие |^каков/i.test(stem)) {
    return `По смыслу вопроса выбираем «${clip(ans, 100)}».`;
  }
  if (/^можно ли|^нужно ли|^следует ли|^является ли/i.test(stem)) {
    return `Ответ на вопрос: «${clip(ans, 80)}».`;
  }
  return `По условию подходит «${clip(ans, 100)}».`;
}

function buildExplain(q) {
  const stem = scrub(q.q);
  const ans = ansOf(q);
  const wrongs = wrongsOf(q);
  const parts = [lead(stem, ans)];

  const fact = firstFact(ANS_FACTS, ans) || firstFact(STEM_FACTS, stem);
  if (fact) parts.push(fact);
  else if (TOPIC[q.topic] && q.topic !== 'Основы') parts.push(TOPIC[q.topic]);

  for (const w of wrongs) {
    const c = contrast(ans, w);
    if (c) {
      parts.push(c);
      break;
    }
  }

  parts.push(`Ответ: <b>${ans}</b>.`);
  return parts.join(' ');
}

